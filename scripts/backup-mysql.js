"use strict";

const fs = require("fs");
const path = require("path");
const mysql = require("mysql2/promise");
const mysqlFormat = require("mysql2");

require("dotenv").config();

function timestamp() {
    return new Date().toISOString().replace(/[-:TZ.]/g, "").slice(0, 14);
}

function sqlValue(value) {
    if (value === null) return "NULL";
    if (Buffer.isBuffer(value)) return `X'${value.toString("hex")}'`;
    if (value instanceof Date) return mysqlFormat.escape(value.toISOString());
    if (typeof value === "object") return mysqlFormat.escape(JSON.stringify(value));
    return mysqlFormat.escape(value);
}

async function main() {
    const backupDirectory = path.resolve(
        process.env.DB_BACKUP_DIR || path.join(__dirname, "..", "backups")
    );
    fs.mkdirSync(backupDirectory, { recursive: true });

    const backupPath = path.join(
        backupDirectory,
        `${process.env.DB_NAME || "database"}-${timestamp()}.sql`
    );
    const connection = await mysql.createConnection({
        host: process.env.DB_HOST,
        port: Number(process.env.DB_PORT || 3306),
        database: process.env.DB_NAME,
        user: process.env.DB_USER,
        password: process.env.DB_PASSWORD,
    });

    try {
        const [tables] = await connection.query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'");
        const output = [
            "-- Logical backup generated by scripts/backup-mysql.js",
            "SET FOREIGN_KEY_CHECKS=0;",
            "",
        ];
        let rowCount = 0;

        for (const tableRow of tables) {
            const tableName = Object.values(tableRow)[0];
            const escapedTable = mysqlFormat.escapeId(tableName);
            const [createRows] = await connection.query(`SHOW CREATE TABLE ${escapedTable}`);
            const createSql = createRows[0]["Create Table"];
            const [rows] = await connection.query(`SELECT * FROM ${escapedTable}`);

            output.push(`DROP TABLE IF EXISTS ${escapedTable};`);
            output.push(`${createSql};`);
            for (const row of rows) {
                const columns = Object.keys(row).map((column) => mysqlFormat.escapeId(column)).join(", ");
                const values = Object.values(row).map(sqlValue).join(", ");
                output.push(`INSERT INTO ${escapedTable} (${columns}) VALUES (${values});`);
            }
            output.push("");
            rowCount += rows.length;
        }

        output.push("SET FOREIGN_KEY_CHECKS=1;");
        fs.writeFileSync(backupPath, `${output.join("\n")}\n`, "utf8");
        const stat = fs.statSync(backupPath);
        if (!stat.isFile() || stat.size === 0) {
            throw new Error(`Backup verification failed for ${backupPath}`);
        }
        console.log(JSON.stringify({ backupPath, tableCount: tables.length, rowCount, bytes: stat.size }));
    } finally {
        await connection.end();
    }
}

main().catch((error) => {
    console.error(`MYSQL_BACKUP_FAILED: ${error.message}`);
    process.exitCode = 1;
});
